import { expect, test } from '@playwright/test'
import type { MasterData } from '../../src/contracts/domain-models'

const { tsImport } = await import('tsx/esm/' + 'api')
const { mkdtemp, rm } = await import('node:fs/' + 'promises')
const { join } = await import('node:' + 'path')
const { tmpdir } = await import('node:' + 'os')
const { once } = await import('node:' + 'events')
const { createMockServer } = await tsImport('../../server/app.ts', import.meta.url)
const { MasterDataSqliteStorage } = await tsImport('../../server/local/master-data-sqlite.ts', import.meta.url)

test('管理员录入真实内容、重载版本、登记引用并验证删除保护', async ({ page }, testInfo) => {
  const directory = await mkdtemp(join(tmpdir(), 'wrj-master-browser-'))
  const storage = new MasterDataSqliteStorage(join(directory, 'master-data.db'))
  const legacyEntries = [{ key: 'noiseFigureDb', valueType: 'NUMBER' as const, value: 3, unit: 'dB' }]
  const legacy: MasterData = {
    dataId: 'COMM-LEGACY-BROWSER', kind: 'COMMUNICATION_SYSTEM', version: 1, referenceCount: 0, active: true,
    content: { name: '旧通信参数', description: '保持历史类型和条目', entries: legacyEntries },
  }
  expect(storage.save(legacy)).toBe(true)
  expect(storage.addReference({ dataId: legacy.dataId, dataVersion: 1, targetType: 'SCENARIO', targetId: 'SCN-001', targetVersion: '1' })).toBe(true)
  const server = createMockServer({ port: 0, masterDataStorage: storage })
  const errors: string[] = []
  try {
    if (!server.httpServer.listening) await once(server.httpServer, 'listening')
    const origin = `http://127.0.0.1:${server.httpServer.address().port}`
    await page.route('**/api/v1/**', async route => {
      const url = new URL(route.request().url())
      const response = await route.fetch({ url: `${origin}${url.pathname}${url.search}`, headers: { ...route.request().headers(), origin: 'http://127.0.0.1:5173' } })
      await route.fulfill({ response, headers: { ...response.headers(), 'access-control-allow-origin': new URL(page.url()).origin } })
    })
    await page.routeWebSocket('**/ws/v1*', () => {})
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await page.goto('/login')
    await page.getByTestId('login-username').fill('admin')
    await page.getByTestId('login-password').fill('123456')
    await page.getByTestId('login-submit').click()
    await page.waitForURL('**/situation')
    await page.goto('/admin?section=master-data&category=master')
    const panel = page.getByTestId('master-data-panel')
    await expect(panel.getByTestId('master-table')).toContainText('COMM-LEGACY-BROWSER')
    await panel.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '通用数据类型筛选', exact: true }) }).click()
    await page.getByRole('option', { name: '体制参数', exact: true }).click()
    await expect(panel.getByTestId('master-table')).toContainText('旧通信参数')
    await panel.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '通用数据类型筛选', exact: true }) }).click()
    await page.getByRole('option', { name: '全部类型', exact: true }).click()
    await panel.getByTestId('master-create').click()
    const create = page.getByRole('dialog', { name: '新增通用数据', exact: true })
    await create.getByTestId('master-save').click()
    await expect(create.getByTestId('master-editor-feedback')).toHaveText('编号不能为空或全是空格。')
    await expect(panel.getByTestId('master-feedback')).toHaveCount(0)
    await expect(page.getByRole('alert').filter({ hasText: '编号不能为空或全是空格。' })).toHaveCount(1)
    await create.getByTestId('master-id').fill('DICT-VALIDATION')
    await create.getByTestId('master-save').click()
    await expect(create.getByTestId('master-editor-feedback')).toHaveText('名称不能为空或全是空格。')
    await create.getByTestId('master-name').fill('校验示例')
    await create.getByTestId('master-save').click()
    await expect(create.getByTestId('master-editor-feedback')).toHaveText('参数条目不能为空，请至少新增并填写一条参数。')
    await expect(create.getByText('填写规则与示例', { exact: true })).toHaveCount(0)
    await expect(create.locator('.master-entries > .maintenance-note')).toHaveCount(0)
    for (let index = 0; index < 10; index++) await create.getByRole('button', { name: '新增条目', exact: true }).click()
    await create.getByTestId('master-save').click()
    await expect(create.getByTestId('master-editor-feedback')).toHaveText('第 1 条参数：参数键不能为空。')
    await expect(create.getByTestId('master-editor-feedback')).toBeInViewport()
    const body = create.locator('.el-dialog__body')
    await expect.poll(() => body.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
    const viewport = page.viewportSize()!
    for (const element of [create, create.locator('.el-dialog__header'), create.locator('.el-dialog__footer')]) {
      const bounds = (await element.boundingBox())!
      expect(bounds.x).toBeGreaterThanOrEqual(0)
      expect(bounds.y).toBeGreaterThanOrEqual(0)
      expect(bounds.x + bounds.width).toBeLessThanOrEqual(viewport.width)
      expect(bounds.y + bounds.height).toBeLessThanOrEqual(viewport.height)
    }
    expect(await body.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await expect(create.getByTestId('master-save')).toBeInViewport()
    await create.getByTestId('master-id').scrollIntoViewIfNeeded()
    await expect(create.getByRole('button', { name: '取消', exact: true })).toBeInViewport()
    await page.screenshot({ path: `output/generic-data-dialog-${testInfo.project.name}.png` })
    await create.getByRole('button', { name: '取消', exact: true }).click()
    await expect(create).not.toBeVisible()
    await expect(panel.getByTestId('master-table')).toContainText('COMM-LEGACY-BROWSER')
    await panel.getByTestId('master-create').click()
    await create.getByTestId('master-id').fill('DICT-BROWSER')
    await create.getByTestId('master-name').fill('测试公共参数')
    await create.getByRole('button', { name: '新增条目' }).click()
    await create.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '参数键', exact: true }) }).click()
    await page.getByRole('option', { name: '接收机噪声系数', exact: true }).click()
    await expect(create.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '参数值类型', exact: true }) })).toContainText('NUMBER')
    await expect(create.getByPlaceholder('单位（可选）')).toHaveValue('dB')
    await create.getByRole('spinbutton', { name: '参数值', exact: true }).fill('6')
    await create.getByRole('button', { name: '新增条目', exact: true }).click()
    const extraEntry = create.locator('.master-entry').nth(1)
    await extraEntry.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '参数键', exact: true }) }).click()
    const optionListId = await extraEntry.getByRole('combobox', { name: '参数键', exact: true }).getAttribute('aria-controls')
    expect(optionListId).toBeTruthy()
    await expect(page.locator(`[id="${optionListId}"]`).getByRole('option', { name: '接收机噪声系数', exact: true })).toBeDisabled()
    await extraEntry.getByRole('button', { name: '移除', exact: true }).click()
    await create.getByTestId('master-save').click()
    await expect(create).not.toBeVisible()
    const row = panel.getByTestId('master-table').locator('.el-table__row').filter({ hasText: 'DICT-BROWSER' })
    await expect(row).toContainText('测试公共参数')
    await row.getByRole('button', { name: '编辑', exact: true }).click()
    const edit = page.getByRole('dialog', { name: '编辑通用数据', exact: true })
    await expect(edit.getByRole('spinbutton', { name: '参数值', exact: true })).toHaveValue('6')
    await edit.getByTestId('master-name').fill('修订公共参数')
    await edit.getByTestId('master-save').click()
    await expect(edit).not.toBeVisible()
    await page.reload()
    await expect(row.locator('td').nth(3)).toHaveText('2')
    await row.getByRole('button', { name: '查看', exact: true }).click()
    const details = page.getByRole('dialog', { name: '通用数据版本与引用记录', exact: true })
    await expect(details.getByTestId('master-history-table').locator('.el-table__row')).toHaveCount(2)
    await details.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '通用数据版本', exact: true }) }).click()
    await page.getByRole('option', { name: '版本 1', exact: true }).click()
    await details.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '引用目标', exact: true }) }).click()
    await page.getByRole('option', { name: /^场景 · .*（SCN-001 \/ \d+）$/ }).click()
    await details.getByRole('button', { name: '登记引用', exact: true }).click()
    await page.getByRole('dialog', { name: '登记通用数据引用', exact: true }).getByRole('button', { name: '确认登记' }).click()
    await expect(details.getByTestId('master-reference-table')).toContainText('SCN-001')
    await expect(details.getByTestId('master-reference-table').locator('.el-table__row')).toHaveCount(1)
    await details.getByRole('button', { name: '关闭', exact: true }).click()
    await expect(row.locator('td').nth(4)).toHaveText('1')
    expect(storage.load().find((row: MasterData) => row.dataId === 'DICT-BROWSER')).toMatchObject({ kind: 'PARAMETER_DICTIONARY', content: { entries: [{ key: 'noiseFigureDb', valueType: 'NUMBER', value: 6, unit: 'dB' }] } })
    expect(storage.details('DICT-BROWSER').history[1].content.entries[0]).toMatchObject({ key: 'noiseFigureDb', value: 6, unit: 'dB' })
    const legacyRow = panel.getByTestId('master-table').locator('.el-table__row').filter({ hasText: 'COMM-LEGACY-BROWSER' })
    await legacyRow.getByRole('button', { name: '编辑', exact: true }).click()
    const legacyEdit = page.getByRole('dialog', { name: '编辑通用数据', exact: true })
    await expect(legacyEdit.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '编辑通用数据类型', exact: true }) })).toContainText('体制参数')
    await expect(legacyEdit.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '参数键', exact: true }) })).toContainText('接收机噪声系数（原有字段）')
    await legacyEdit.getByTestId('master-name').fill('修订旧通信参数')
    await legacyEdit.getByTestId('master-save').click()
    await expect(legacyEdit).not.toBeVisible()
    await page.reload()
    expect(storage.load().find((row: MasterData) => row.dataId === legacy.dataId)).toMatchObject({ kind: 'COMMUNICATION_SYSTEM', content: { name: '修订旧通信参数', entries: legacyEntries } })
    expect(storage.details(legacy.dataId).history).toHaveLength(2)
    expect(storage.details(legacy.dataId).references).toHaveLength(1)
    expect(errors).toEqual([])
    await row.getByRole('button', { name: '删除', exact: true }).click()
    const blocked = page.waitForResponse(response => response.request().method() === 'DELETE' && response.url().endsWith('/admin/master-data/DICT-BROWSER'))
    await page.getByRole('dialog', { name: '删除通用数据', exact: true }).getByRole('button', { name: '确认删除' }).click()
    expect((await blocked).status()).toBe(409)
    await expect(panel.getByTestId('master-feedback')).toContainText('不能删除')
    await expect(row).toHaveCount(1)
    // 由公开 API 验证越权，不用篡改前端角色制造证据。
    const forbidden = await page.request.get(`${origin}/api/v1/admin/master-data`, { headers: { Origin: 'http://127.0.0.1:5173', 'X-Demo-Role': 'OPERATOR' } })
    expect(forbidden.status()).toBe(403)
    // 只允许本次明确的引用保护 DELETE 409 所产生的浏览器资源错误。
    expect(errors).toEqual(['Failed to load resource: the server responded with a status of 409 (Conflict)'])
  } finally {
    await page.close()
    await server.close()
    storage.close()
    await rm(directory, { recursive: true, force: true })
  }
})
