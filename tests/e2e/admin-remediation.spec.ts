import { expect, test } from '@playwright/test'

const { tsImport } = await import('tsx/esm/' + 'api')
const { mkdtemp, readFile, rm } = await import('node:fs/' + 'promises')
const { join } = await import('node:' + 'path')
const { tmpdir } = await import('node:' + 'os')
const { once } = await import('node:' + 'events')
const { createMockServer } = await tsImport('../../server/app.ts', import.meta.url)
const { EquipmentSqliteStorage } = await tsImport('../../server/local/equipment-sqlite.ts', import.meta.url)

test('设备停用/恢复持久化，日志操作类型查询与下载一致', async ({ page }, testInfo) => {
  const directory = await mkdtemp(join(tmpdir(), 'wrj-admin-remediation-'))
  const storage = new EquipmentSqliteStorage(join(directory, 'equipment.db'))
  const server = createMockServer({ port: 0, equipmentStorage: storage })
  const errors: string[] = []
  try {
    if (!server.httpServer.listening) await once(server.httpServer, 'listening')
    const origin = `http://127.0.0.1:${server.httpServer.address().port}`
    await page.route('**/api/v1/**', async route => {
      const url = new URL(route.request().url())
      const response = await route.fetch({ url: `${origin}${url.pathname}${url.search}`, headers: { ...route.request().headers(), origin: 'http://127.0.0.1:5173' } })
      await route.fulfill({ response, headers: { ...response.headers(), 'access-control-allow-origin': new URL(page.url()).origin } })
    })
    await page.routeWebSocket('**/ws/v1', () => {})
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/login')
    await page.getByTestId('login-username').fill('admin')
    await page.getByTestId('login-password').fill('123456')
    await page.getByTestId('login-submit').click()
    await page.waitForURL('**/situation')
    await page.goto('/admin?section=master-data&category=equipment')
    await page.getByTestId('equipment-create').click()
    await page.getByTestId('equipment-id').fill('EQ-BROWSER-STATUS')
    await page.getByTestId('equipment-type').click()
    await page.getByRole('option', { name: '微波通信设备', exact: true }).click()
    await page.getByTestId('equipment-save').click()
    const table = page.getByTestId('equipment-table')
    const row = table.locator('.el-table__row').filter({ hasText: 'EQ-BROWSER-STATUS' })
    await expect(row).toContainText('已启用')
    await row.getByRole('button', { name: '停用', exact: true }).click()
    await expect(row).toContainText('已停用')
    expect(storage.load()[0].active).toBe(false)
    await page.reload()
    await expect(row).toContainText('已停用')
    await row.getByRole('button', { name: '恢复', exact: true }).click()
    await expect(row).toContainText('已启用')
    expect(storage.load()[0].active).toBe(true)
    await page.goto('/admin?section=audit-logs')
    const filter = page.getByTestId('audit-action-filter')
    await filter.click()
    await page.getByRole('option', { name: '停用装备参数', exact: true }).click()
    await page.getByRole('button', { name: '查询', exact: true }).click()
    const logs = page.getByTestId('audit-table').locator('.el-table__row')
    await expect(logs).toHaveCount(1)
    for (const log of await logs.all()) await expect(log).toContainText('停用装备参数')
    const panel = page.getByTestId('audit-log-panel')
    const box = await panel.boundingBox()
    expect(box!.x + box!.width).toBeLessThanOrEqual(testInfo.project.use.viewport!.width)
    await page.screenshot({ path: testInfo.outputPath('audit-action-filter.png'), fullPage: true })
    await page.getByRole('button', { name: '导出日志', exact: true }).click()
    await expect(page.getByRole('dialog', { name: '确认导出审计日志' })).toBeVisible()
    const downloaded = page.waitForEvent('download')
    await page.getByTestId('confirm-audit-export').click()
    const file = await downloaded
    const text = await readFile((await file.path())!, 'utf8')
    expect(text).toContain('MASTER_DATA_EQUIPMENT_DISABLE')
    expect(text).not.toContain('MASTER_DATA_EQUIPMENT_ENABLE')
    expect(text).not.toContain('MASTER_DATA_EQUIPMENT_CREATE')
    await expect(page.getByTestId('audit-export-status')).toContainText('1')
    expect(errors).toEqual([])
  } finally {
    await page.close()
    await server.close()
    storage.close()
    await rm(directory, { recursive: true, force: true })
  }
})
