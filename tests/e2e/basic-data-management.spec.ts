import { expect, test, type Page } from '@playwright/test'
import type { EquipmentParameter, MasterData } from '../../src/contracts/domain-models'

const { tsImport } = await import('tsx/esm/' + 'api')
const { mkdtemp, rm } = await import('node:fs/' + 'promises')
const { join } = await import('node:' + 'path')
const { tmpdir } = await import('node:' + 'os')
const { once } = await import('node:' + 'events')
const { createMockServer } = await tsImport('../../server/app.ts', import.meta.url)
const { EquipmentSqliteStorage } = await tsImport('../../server/local/equipment-sqlite.ts', import.meta.url)
const { MasterDataSqliteStorage } = await tsImport('../../server/local/master-data-sqlite.ts', import.meta.url)

async function selectMasterKind(page: Page, label: string): Promise<void> {
  await page.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '通用数据类型筛选', exact: true }) }).click()
  await page.getByRole('option', { name: label, exact: true }).click()
}

async function createMasterData(page: Page, dataId: string, name: string, kind: '体制参数' | '参数字典' | '枚举'): Promise<void> {
  await page.getByTestId('master-create').click()
  const dialog = page.getByRole('dialog', { name: '新增通用数据', exact: true })
  await dialog.getByTestId('master-id').fill(dataId)
  await dialog.getByTestId('master-name').fill(name)
  await dialog.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '编辑通用数据类型', exact: true }) }).click()
  await page.getByRole('option', { name: kind, exact: true }).click()
  await dialog.getByRole('button', { name: '新增条目', exact: true }).click()
  if (kind !== '枚举') {
    await dialog.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '参数键', exact: true }) }).click()
    const communication = kind === '体制参数'
    await expect(page.getByRole('option', { name: communication ? '接收机噪声系数' : '发射频率', exact: true })).toHaveCount(0)
    await page.getByRole('option', { name: communication ? '发射频率' : '接收机噪声系数', exact: true }).click()
    await dialog.getByRole('spinbutton', { name: '参数值', exact: true }).fill(communication ? '2200' : '6')
  } else {
    await dialog.getByRole('textbox', { name: '参数键', exact: true }).fill('mode')
    await dialog.getByPlaceholder('文本值').fill(name)
  }
  await dialog.getByTestId('master-save').click()
  await expect(dialog).toBeHidden()
}

test('GNZB-28 基础数据管理在双视口分别维护设备、体制、字典与枚举', async ({ page }) => {
  const directory = await mkdtemp(join(tmpdir(), 'wrj-basic-data-browser-'))
  const equipment = new EquipmentSqliteStorage(join(directory, 'equipment.db'))
  const master = new MasterDataSqliteStorage(join(directory, 'master-data.db'))
  const server = createMockServer({ port: 0, equipmentStorage: equipment, masterDataStorage: master })
  const errors: string[] = []
  try {
    if (!server.httpServer.listening) await once(server.httpServer, 'listening')
    const origin = `http://127.0.0.1:${server.httpServer.address().port}`
    await page.route('**/api/v1/**', async route => {
      const url = new URL(route.request().url())
      const response = await route.fetch({ url: `${origin}${url.pathname}${url.search}`, headers: { ...route.request().headers(), origin: 'http://127.0.0.1:5173' } })
      await route.fulfill({ response, headers: { ...response.headers(), 'access-control-allow-origin': new URL(page.url()).origin } })
    })
    await page.routeWebSocket('**/ws/v1*', () => {})
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })

    await page.goto('/login')
    await page.getByTestId('login-username').fill('admin')
    await page.getByTestId('login-password').fill('123456')
    await page.getByTestId('login-submit').click()
    await page.waitForURL('**/situation')
    await page.goto('/admin?section=master-data&category=equipment')
    const systemNavigation = page.getByRole('complementary', { name: '系统管理导航' })
    await expect(systemNavigation.getByRole('menuitem', { name: '基础数据管理', exact: true })).toHaveCount(1)
    await expect(systemNavigation.getByRole('menuitem', { name: '装备参数库', exact: true })).toHaveCount(0)

    await page.getByRole('tab', { name: '设备参数', exact: true }).click()
    const equipmentTable = page.getByTestId('equipment-table')
    await expect(equipmentTable).toContainText('暂无数据')
    await page.getByTestId('equipment-create').click()
    const equipmentDialog = page.getByRole('dialog', { name: '新增装备参数', exact: true })
    await equipmentDialog.getByTestId('equipment-id').fill('EQ-BASIC-E2E')
    await equipmentDialog.getByTestId('equipment-type').click()
    await page.getByRole('option', { name: '微波通信设备', exact: true }).click()
    await equipmentDialog.getByTestId('equipment-frequency-min').locator('input').fill('1')
    await equipmentDialog.getByTestId('equipment-frequency-max').locator('input').fill('1')
    await equipmentDialog.getByTestId('equipment-modulation').click()
    await page.getByRole('option', { name: 'QPSK', exact: true }).click()
    await equipmentDialog.getByTestId('equipment-bandwidth').locator('input').fill('1')
    await equipmentDialog.getByTestId('equipment-power').locator('input').fill('100')
    await equipmentDialog.getByTestId('equipment-data-rate').click()
    await page.getByRole('option', { name: '80 Mbps', exact: true }).click()
    await equipmentDialog.getByTestId('equipment-threshold').locator('input').fill('1')
    await equipmentDialog.getByTestId('equipment-save').click()
    const equipmentRow = equipmentTable.locator('.el-table__row').filter({ hasText: 'EQ-BASIC-E2E' })
    await expect(equipmentRow).toContainText('微波通信设备')
    await expect(equipmentRow).toContainText('QPSK')
    await expect(equipmentRow).toContainText('80 Mbps')
    expect((equipment.load() as EquipmentParameter[]).find((row) => row.equipmentId === 'EQ-BASIC-E2E')).toMatchObject({
      frequencyMinMHz: 1, frequencyMaxMHz: 1, bandwidthMHz: 1, txPowerW: 100, dataRateMbps: 80, modulation: 'QPSK', berThreshold: 1,
    })

    await equipmentRow.getByRole('button', { name: '编辑', exact: true }).click()
    const editEquipment = page.getByRole('dialog', { name: '编辑装备参数', exact: true })
    await editEquipment.getByTestId('equipment-type').click()
    await page.getByRole('option', { name: '卫星通信设备', exact: true }).click()
    await expect(editEquipment).toContainText('数据速率与设备类型不一致，请选择对应的速率档位或清空。')
    await expect(editEquipment.getByTestId('equipment-save')).toBeDisabled()
    await editEquipment.getByTestId('equipment-data-rate').click()
    await page.getByRole('option', { name: '16 kbps（天通）', exact: true }).click()
    await editEquipment.getByTestId('equipment-save').click()
    await page.reload()
    await expect(equipmentRow).toContainText('卫星通信设备')
    await expect(equipmentRow).toContainText('QPSK')
    await expect(equipmentRow).toContainText('16 kbps')
    expect((equipment.load() as EquipmentParameter[]).find((row) => row.equipmentId === 'EQ-BASIC-E2E')).toMatchObject({ version: 2, type: '卫星通信设备', modulation: 'QPSK', dataRateMbps: 0.016, active: true })

    await equipmentRow.getByRole('button', { name: '停用', exact: true }).click()
    await expect(equipmentRow).toContainText('已停用')
    await equipmentRow.getByRole('button', { name: '恢复', exact: true }).click()
    await expect(equipmentRow).toContainText('已启用')
    await equipmentRow.getByRole('button', { name: '查看', exact: true }).click()
    const equipmentDetails = page.getByRole('dialog', { name: '查看参数详情', exact: true })
    await expect(equipmentDetails).toContainText('调制方式')
    await expect(equipmentDetails).toContainText('QPSK')
    await expect(equipmentDetails).toContainText('16 kbps')
    await expect(equipmentDetails.getByTestId('equipment-relations')).toContainText('版本历史')
    await expect(equipmentDetails.getByTestId('equipment-relations')).toContainText('场景引用')
    await equipmentDetails.getByRole('button', { name: '关闭', exact: true }).click()

    await equipmentRow.getByRole('button', { name: '编辑', exact: true }).click()
    const clearEquipment = page.getByRole('dialog', { name: '编辑装备参数', exact: true })
    await clearEquipment.getByTestId('equipment-modulation').locator('.el-select__wrapper').hover()
    await clearEquipment.getByTestId('equipment-modulation').locator('.el-select__clear').click()
    await clearEquipment.getByTestId('equipment-save').click()
    await page.reload()
    await expect(equipmentRow).toContainText('暂无数据')
    expect((equipment.load() as EquipmentParameter[]).find((row) => row.equipmentId === 'EQ-BASIC-E2E')).toMatchObject({ version: 5, modulation: null, active: true })

    await page.getByTestId('equipment-create').click()
    const rateVariants = page.getByRole('dialog', { name: '新增装备参数', exact: true })
    await rateVariants.getByTestId('equipment-type').click()
    await page.getByRole('option', { name: '数传通信设备', exact: true }).click()
    await rateVariants.getByTestId('equipment-data-rate').click()
    await expect(page.getByRole('option', { name: '6.4 kbps（L 波段前向）', exact: true })).toBeVisible()
    await expect(page.getByRole('option', { name: '16 Mbps（C 波段返向）', exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await rateVariants.getByTestId('equipment-type').click()
    await page.getByRole('option', { name: '光纤通信设备', exact: true }).click()
    await rateVariants.getByTestId('equipment-data-rate').locator('input').fill('9')
    await expect(rateVariants).toContainText('光纤数据速率必须在 10～1000 Mbps 之间。')
    await expect(rateVariants.getByTestId('equipment-save')).toBeDisabled()
    await rateVariants.getByTestId('equipment-type').click()
    await page.getByRole('option', { name: '微波通信设备', exact: true }).click()
    await rateVariants.getByTestId('equipment-frequency-min').locator('input').fill('0')
    await rateVariants.getByTestId('equipment-frequency-max').locator('input').fill('1')
    await rateVariants.getByTestId('equipment-bandwidth').locator('input').fill('0')
    await rateVariants.getByTestId('equipment-power').locator('input').fill('101')
    await rateVariants.getByTestId('equipment-threshold').locator('input').fill('1.000001')
    await expect(rateVariants).toContainText('频率必须为有限正数，未配置请留空。')
    await expect(rateVariants).toContainText('发射带宽必须为有限正数，未配置请留空。')
    await expect(rateVariants).toContainText('发射功率不能超过 100 W。')
    await expect(rateVariants).toContainText('BER 阈值必须在 0～1 之间。')
    await expect(rateVariants.getByTestId('equipment-save')).toBeDisabled()
    await rateVariants.getByTestId('equipment-frequency-min').locator('input').fill('2')
    await expect(rateVariants).toContainText('频率上限不得小于下限。')
    await rateVariants.getByTestId('equipment-type').click()
    await page.getByRole('option', { name: '激光通信设备', exact: true }).click()
    await rateVariants.getByTestId('equipment-modulation').click()
    await expect(page.getByRole('option', { name: 'OOK', exact: true })).toBeVisible()
    await page.getByRole('option', { name: 'OOK', exact: true }).click()
    await rateVariants.getByTestId('equipment-threshold').locator('input').fill('1')
    await rateVariants.getByTestId('equipment-data-rate').locator('input').fill('0')
    await expect(rateVariants).toContainText('数据速率必须大于 0 Mbps，未配置请留空。')
    await expect(rateVariants.getByTestId('equipment-save')).toBeDisabled()
    await rateVariants.getByRole('button', { name: '取消', exact: true }).click()

    await page.getByRole('tab', { name: '通用基础数据', exact: true }).click()
    const masterPanel = page.getByTestId('master-data-panel')
    await createMasterData(page, 'COMM-BASIC-E2E', '浏览器体制参数', '体制参数')
    await createMasterData(page, 'DICT-BASIC-E2E', '浏览器参数字典', '参数字典')
    await createMasterData(page, 'ENUM-BASIC-E2E', '浏览器枚举', '枚举')

    const masterTable = masterPanel.getByTestId('master-table')
    await selectMasterKind(page, '体制参数')
    await expect(masterTable).toContainText('COMM-BASIC-E2E')
    await expect(masterTable).not.toContainText('DICT-BASIC-E2E')
    await expect(masterTable).not.toContainText('ENUM-BASIC-E2E')
    await selectMasterKind(page, '参数字典')
    await expect(masterTable).toContainText('DICT-BASIC-E2E')
    await expect(masterTable).not.toContainText('COMM-BASIC-E2E')
    await expect(masterTable).not.toContainText('ENUM-BASIC-E2E')
    await selectMasterKind(page, '枚举')
    await expect(masterTable).toContainText('ENUM-BASIC-E2E')
    await expect(masterTable).not.toContainText('COMM-BASIC-E2E')

    await page.getByRole('tab', { name: '设备参数', exact: true }).click()
    await expect(page.getByTestId('equipment-table')).toContainText('EQ-BASIC-E2E')
    await page.getByRole('tab', { name: '通用基础数据', exact: true }).click()
    await selectMasterKind(page, '参数字典')
    await expect(page.getByTestId('master-table')).toContainText('DICT-BASIC-E2E')
    await page.reload()
    await selectMasterKind(page, '参数字典')
    await expect(page.getByTestId('master-table')).toContainText('DICT-BASIC-E2E')
    expect((master.load() as MasterData[]).map((row) => ({ dataId: row.dataId, kind: row.kind }))).toEqual([
      { dataId: 'COMM-BASIC-E2E', kind: 'COMMUNICATION_SYSTEM' },
      { dataId: 'DICT-BASIC-E2E', kind: 'PARAMETER_DICTIONARY' },
      { dataId: 'ENUM-BASIC-E2E', kind: 'ENUMERATION' },
    ])
    expect(errors).toEqual([])
  } finally {
    await page.close()
    await server.close()
    equipment.close()
    master.close()
    await rm(directory, { recursive: true, force: true })
  }
})
